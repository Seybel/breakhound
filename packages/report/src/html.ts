import type { ScanResult } from '@breakhound/engine';
import { MARK_PNG, WORDMARK_PNG } from './brand';
import { DETECTOR_LABELS, groupIssues, leftOutHint, openInstruction, routeLabel } from './format';
import { renderPrompt } from './markdown';

export interface HtmlOptions {
  /** Screenshot file name -> data URI (or URL) to show for it. */
  images?: Map<string, string>;
  /** Command shown in the prompt for re-checking. */
  verifyCommand?: string;
}

/** Data embedded in the page; the page renders itself from this. */
function buildData(result: ScanResult, options: HtmlOptions) {
  const images = options.images ?? new Map<string, string>();
  const groups = groupIssues(result).map((g) => ({
    fingerprint: g.fingerprint,
    severity: g.issue.severity,
    detector: g.issue.detector,
    detectorLabel: DETECTOR_LABELS[g.issue.detector],
    title: g.issue.title,
    ranges: g.issue.ranges,
    worstAt: g.issue.worstAt,
    element: g.issue.element,
    related: g.issue.related ?? null,
    evidence: g.issue.evidence,
    styles: g.issue.styles,
    suggestion: g.issue.suggestion ?? null,
    openFirst: g.issue.state ? openInstruction(g.issue.state).replace(/`/g, '') : null,
    screenshot: g.issue.screenshot ? (images.get(g.issue.screenshot) ?? null) : null,
    pages: g.routes.map((r) => ({
      route: routeLabel(r.route),
      url: r.route.url,
      ranges: r.issue.ranges,
    })),
    prompt: renderPrompt(result, {
      fingerprints: [g.fingerprint],
      severities: ['error', 'warning', 'info'],
      ...(options.verifyCommand ? { verifyCommand: options.verifyCommand } : {}),
    }),
  }));
  return {
    meta: {
      version: result.tool.version,
      startedAt: result.startedAt,
      durationMs: result.durationMs,
      minWidth: result.settings.minWidth,
      maxWidth: result.settings.maxWidth,
      baseUrl: result.project.baseUrl,
    },
    summary: result.summary,
    leftOutHint: leftOutHint(result.routes),
    routes: result.routes.map((r) => ({
      route: routeLabel(r),
      url: r.url,
      status: r.status,
      error: r.error ?? null,
      warnings: r.warnings ?? [],
      breakpoints: r.breakpoints,
      issues: r.issues.map((i) => ({
        fingerprint: i.fingerprint,
        severity: i.severity,
        ranges: i.ranges,
        title: i.title,
      })),
    })),
    groups,
    prompt: renderPrompt(
      result,
      options.verifyCommand ? { verifyCommand: options.verifyCommand } : {},
    ),
  };
}

function embedJson(value: unknown): string {
  // Safe inside <script>: no "</script>", and no raw line/paragraph separators.
  return JSON.stringify(value)
    .replace(/</g, '\\u003c')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

